const fs = require('node:fs')
const assert = require('node:assert/strict')
const manifest = fs.readFileSync('src/releases/adminPortalRelease.js', 'utf8')
const dialog = fs.readFileSync('src/components/AdminPortalReleaseControl.jsx', 'utf8')
const admin = fs.readFileSync('src/pages/AdminPortal.jsx', 'utf8')
const version = manifest.match(/version:\s*'([^']+)'/)?.[1]
assert.ok(version && /^3[.]0[.]0/.test(version), 'Baseline must use semantic v3.0.0')
assert.match(manifest, /productionDate: null/)
assert.match(admin, /import AdminPortalReleaseControl/)
assert.match(admin, /<AdminPortalReleaseControl/)
assert.match(dialog, /RomyLabs Admin · v/)
assert.match(dialog, /createPortal/)
assert.match(dialog, /document[.]body/)
assert.match(dialog, /position:'fixed'/)
assert.match(dialog, /aria-modal="true"/)
assert.match(dialog, /role="dialog"/)
assert.match(dialog, /document[.]body[.]style[.]overflow/)
assert.match(dialog, /event[.]key === 'Escape'/)
assert.match(dialog, /event[.]target === event[.]currentTarget/)
assert.doesNotMatch(manifest, /Nashville|TCR|Arcvena|BocaSync|RestoreRelay|Camvella|Oculivo|GroundIVO|IRS|transcripts|payments|seat counts/i)
const packageVersion = JSON.parse(fs.readFileSync('package.json', 'utf8')).version
assert.match(packageVersion, /^3[.]\d+[.]\d+$/, 'Shared CRM package must remain on semantic major version 3 while Admin Portal tracks independently')
console.log('PASS: Admin Portal v3.0.0 release baseline and dialog guard')
