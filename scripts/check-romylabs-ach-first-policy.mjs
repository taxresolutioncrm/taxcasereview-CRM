import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const api=readFileSync('supabase/functions/romylabs-stripe-checkout/index.ts','utf8')
const hook=readFileSync('supabase/functions/romylabs-stripe-webhook/index.ts','utf8')
const ui=readFileSync('src/components/admin/RomyLabsStripeSettings.jsx','utf8')
const required=(s,x,message)=>assert.ok(s.includes(x),message)
required(api,"if(action==='checkout')return json",'Old mixed card / ACH invoice checkout is disabled')
required(api,"if(action==='checkout_ach')",'Invoice checkout supports ACH-only mode')
required(api,"'payment_method_types[0]':'us_bank_account'",'ACH is the only newly authorized payment method')
assert.ok(!api.includes("'payment_method_types[0]':'card'"),'No new subscription can silently absorb card fees')
required(api,"romylabs-invoice-ach-",'Separate idempotency key for ACH-only checkout')
required(api,"payment_method:'us_bank_account',card_surcharge_cents:0",'ACH response must explicitly disclose no surcharge')
required(api,"legacy_card_link_blocked",'Preexisting card-enabled links must not be silently reused for new offices')
required(api,"'metadata[romylabs_payment_method_policy]':'ach_no_surcharge_v1'",'Tagged ACH subscription links')
required(hook,"'checkout.session.async_payment_succeeded'].includes(event.type)",'ACH recurring subscription scheduling must await successful bank payment')
required(hook,"event.data?.object?.payment_status==='paid'",'Unpaid ACH sessions may not initiate subscription settlement')
required(ui,"action:'checkout_ach'",'UI must use ACH-only Checkout action')
required(ui,'Copy ACH Link','UI must label ACH payment options')
required(ui,'Credit-card processing fees are the office','Display merchant fee policy')
console.log('PASS RomyLabs ACH-first invoice policy and async settlement safeguards')
