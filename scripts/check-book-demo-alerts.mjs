// Lightweight non-mutating regression gate for every central RomyLabs Book Demo route.
// Run: node scripts/check-book-demo-alerts.mjs
import { readFileSync } from 'node:fs'
import assert from 'node:assert/strict'
const read=p=>readFileSync(p,'utf8')
const cfg=read('src/lib/productBookingConfig.js')
const book=read('src/pages/BookAppointment.jsx')
const mail=read('supabase/functions/send-email/index.ts')
const alert=read('src/components/AdminBookingAlerts.jsx')
const shell=read('src/pages/AdminPortal.jsx')
const migration=read('supabase/migrations/20261030183000_romylabs_durable_booking_alerts.sql')
const brand=read('supabase/migrations/20261030183500_fix_central_demo_branding.sql')
const keys=['taxres_crm','romylabs','camvella','arcvena','bocasync','oculivo','groundivo','restore_relay','pool_crm','barbers_salons','health_insurance']
for (const key of keys) {
  assert.match(cfg,new RegExp('\\b'+key+':\\s*\\{'),'Missing booking config: '+key)
  assert.match(brand,new RegExp(key==='taxres_crm'?'\\[TaxRes CRM\\]':key==='restore_relay'?'\\[Restore Relay\\]':key==='romylabs'?'\\[RomyLabs\\]':key==='camvella'?'\\[Camvella\\]':key==='arcvena'?'\\[Arcvena\\]':key==='bocasync'?'\\[BocaSync\\]':key==='oculivo'?'\\[Oculivo\\]' :key==='groundivo'?'\\[GroundIVO\\]':key==='pool_crm'?'\\[PoolVerge\\]':key==='barbers_salons'?'\\[Barbers & Salons CRM\\]':'\\[Health Insurance Agency CRM\\]'),'Missing calendar brand: '+key)
}
assert.ok(book.includes("booking_create_product"),'booking writes must persist product identity')
assert.ok(book.includes("productCfg.key==='taxres_crm'?productCfg.favicon:(data.logo_url||productCfg.favicon)"),'TaxRes booking favicon must not be overridden by tenant logo metadata')
assert.ok(book.includes("booking_firm_notification"),'firm notification must be requested')
assert.ok(book.includes("booking_confirmation"),'client confirmation must be requested')
assert.ok(cfg.includes("productParam === 'aquagrid'"),'Legacy PoolVerge alias missing')
assert.ok(mail.includes("booking_token"),'mail must validate booking token')
assert.ok(mail.includes("romylabs_stalwart_transport_for_product"),'Internal bookings must use RomyLabs Stalwart')
assert.ok(mail.includes("notification_submission_id"),'Stalwart submission must be auditable')
assert.ok(mail.includes("camvella: { name: 'Camvella', email: 'romy@camvella.com' }"),'Camvella booking mailbox routing must not regress')
assert.ok(migration.includes("after insert or update of product_id,status"),'durable booking trigger missing')
assert.ok(migration.includes("on conflict (booking_id) do nothing"),'idempotent recent booking backfill missing')
assert.ok(alert.includes("acknowledged_at"),'in-app review state missing')
assert.ok(shell.includes('<AdminBookingAlerts workspace />'),'Demo alerts must be mounted within the Tasks workspace')
assert.ok(!shell.includes('<AdminBookingAlerts />'),'Global booking alert banner must not cover other Admin Portal pages')
assert.ok(migration.includes('followup_status text not null'),'Demo follow-up lifecycle missing')
assert.ok(migration.includes('contact_outcome'),'Contact outcome data missing')
assert.ok(migration.includes('guard_romylabs_booking_followup'),'Completion guard missing')
assert.ok(alert.includes('markContacted(item)'),'Record-contact workflow missing')
assert.ok(alert.includes('complete(item)'),'Complete-task workflow missing')
assert.ok(alert.includes(".in('followup_status',showCompleted?['new','acknowledged','contacted','completed']:['new','acknowledged','contacted'])"),'Unfinished leads must remain visible and completed history must be optional')
const dueMigration=read('supabase/migrations/20261030235900_romylabs_demo_followup_deadlines.sql')
assert.ok(dueMigration.includes('followup_due_at'),'Task due date migration missing')
assert.ok(alert.includes('assigned_to:draft.assigned_to.trim()'),'Owner reassignment must save from explicit draft')
assert.ok(alert.includes('followup_due_at:due.toISOString()'),'Task deadline must save selected calendar date and time')
assert.ok(alert.includes('Include completed follow-ups'),'Completed history not available')
assert.ok(shell.includes("path:'/crm-admin/tasks'"),'Admin sidebar Tasks tab missing')
assert.ok(shell.includes('<Route path="/tasks"'),'Admin Tasks page route missing')
assert.ok(alert.includes('workspace=false'),'Task workspace display mode missing')
assert.ok(alert.includes("onClick={()=>setTaskFilter(filter)}"),'Task metric cards must filter the follow-up list')
assert.ok(alert.includes("type=\"date\" onClick={e=>e.currentTarget.showPicker?.()}"),'Task deadline must provide a clickable calendar')
assert.ok(alert.includes("type=\"time\""),'Task deadline time picker missing')
assert.ok(alert.includes("onClick={()=>saveTask(item)}"),'Explicit Save changes action missing')
assert.ok(alert.includes("romylabs_record_booking_activity"),'Contact actions must write through transaction')
assert.ok(alert.includes("romylabs_booking_activities"),'Contact timeline must query persisted activity')
assert.ok(alert.includes("View activity history"),'Activity timeline disclosure missing')
assert.ok(alert.includes("Save activity"),'Contact logging must use a named save action')
assert.ok(alert.includes('aria-expanded={expandedTask===item.booking_id}'),'Each follow-up must have an accessible expand toggle')
assert.ok(alert.includes('expandedTask===item.booking_id && <>'),'Actions and activity details must stay collapsed until requested')
assert.ok(alert.includes('Task status for '),'Editable task status selector missing')
assert.ok(alert.includes('followup_status:status'),'Status save must persist to existing booking alert record')
assert.ok(alert.includes('Done / Closed'),'Completed task option missing')
assert.ok(alert.includes('Please log the contact details first using Log activity / Update status'),'Contact-first completion safeguard missing')
assert.ok(alert.includes('<option value="contacted">Contacted</option>'),'Contacted option must be selectable')
assert.ok(alert.includes('<option value="completed">Done / Closed</option>'),'Done option must be selectable')
console.log('PASS — 11 central booking products, labels, mail invocation, durable alerts and Admin Portal visibility')
