const route=readFileSync('supabase/functions/romylabs-ivr-route/index.ts','utf8')
const voicemail=readFileSync('supabase/functions/romylabs-voicemail-prompt/index.ts','utf8')
const migration=readFileSync('supabase/migrations/20261116030000_romylabs_ivr_voicemail_settings.sql','utf8')
must("['ivr','IVR & Voicemail Settings',0]",'IVR settings must be available from Communications tabs')
must("action:'ivr_settings_get'",'IVR settings must read from the real server')
must("action:'ivr_settings_save'",'IVR settings must save through the real server')
must('Unsaved changes','Unsaved IVR edits must be visible')
