const must=(needle,reason)=>assert.ok(ui.includes(needle),reason)
must('startCall, endCall, cancelCall, sendDTMF,','Dial pad must use existing SignalWire call context')
must('function pressDialDigit(digit)','Dial pad must implement real digit handling')
