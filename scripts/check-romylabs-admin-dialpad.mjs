assert.ok(migration.includes('enable row level security')&&migration.includes('revoke all on public.romylabs_ivr_settings from public,anon,authenticated'),'IVR config must be private')
assert.ok(migration.includes("a0000000-0000-0000-0000-000000000001"),'IVR configuration must be RomyLabs tenant-scoped')
console.log('PASS RomyLabs communications keypad and responsive UI contracts')
