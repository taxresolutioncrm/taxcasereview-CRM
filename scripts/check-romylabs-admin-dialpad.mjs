assert.ok(receive.includes("romylabs_ivr_settings")&&receive.includes('escapeXml(ivrConfig.menu_greeting)')&&receive.includes("businessHours(new Date(),ivr)"),'Inbound menu uses persisted greeting and Eastern hours')
