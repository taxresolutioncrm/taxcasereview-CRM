const fs = require('fs')
const assert = require('assert')

const migration = fs.readFileSync('supabase/migrations/20261023121000_note_edit_audit_history.sql','utf8')
const component = fs.readFileSync('src/components/EditableNote.jsx','utf8')
const clients = fs.readFileSync('src/pages/Clients.jsx','utf8')
const leads = fs.readFileSync('src/pages/Leads.jsx','utf8')
const cases = fs.readFileSync('src/pages/Cases.jsx','utf8')

for (const table of ['client_notes','lead_notes','case_notes']) {
  assert(migration.includes('alter table public.'+table), table+' metadata migration missing')
}
assert(migration.includes('alter column case_id type text'), 'case_notes.case_id must match text cases.id')
assert(migration.includes('create table if not exists public.note_edit_audit'), 'audit table missing')
assert(migration.includes('for update'), 'row lock missing')
assert(migration.includes('p_expected_version'), 'optimistic concurrency version missing')
assert(migration.includes('current_employee_permission'), 'backend permission enforcement missing')
assert(migration.includes("set_config('app.note_edit_rpc','1',true)"), 'guarded RPC context missing')
assert(migration.includes('revoke all on public.note_edit_audit'), 'audit append-only grants missing')
assert(migration.includes('get_note_edit_history'), 'admin audit history RPC missing')
assert(component.includes("supabase.rpc('edit_employee_note'"), 'UI does not use audited RPC')
assert(component.includes('Note cannot be empty.'), 'empty-note UI guard missing')
assert(component.includes('Last edited by:'), 'last-edit display missing')
assert(clients.includes('<EditableNote') && clients.includes('kind="client"'), 'client notes edit UI missing')
assert(leads.includes('<EditableNote') && leads.includes('kind="lead"'), 'lead notes edit UI missing')
assert(cases.includes('<EditableNote') && cases.includes('kind="case"'), 'case notes edit UI missing')
assert(cases.includes('note: newNote.trim()') && cases.includes('author: actor'), 'case note schema mismatch not corrected')
assert(!cases.includes('text: newNote.trim(),\n      created_by: actor'), 'legacy case note write shape remains')
console.log('PASS note edit/audit static regression checks')
