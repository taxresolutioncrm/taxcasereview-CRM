import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const clients=readFileSync('src/pages/Clients.jsx','utf8')
const hotfix=readFileSync('public/romylabs-admin-hotfix.js','utf8')
const marker=JSON.parse(readFileSync('public/taxres-build.json','utf8')).build
const html=readFileSync('index.html','utf8')
const dashboard=readFileSync('src/pages/Dashboard.jsx','utf8')
const roster=clients.slice(clients.indexOf("placeholder=\"Search clients…\"")-140,clients.indexOf("placeholder=\"Search clients…\"")+1300)
const requireCheck=(condition,message)=>assert(condition,message)
requireCheck(roster.includes('type="text"'),'Roster search must not use type=search (double clear icons)')
requireCheck(!roster.includes('type="search"'),'No native Chrome clear icon')
requireCheck(roster.includes('aria-label="Search client roster"'),'Accessible roster search')
requireCheck(clients.includes('clientSearch.length>0 && <button'),'Only show one custom clear button while query is nonempty')
requireCheck(clients.includes('aria-label="Clear client roster search"'),'Accessible clear button')
requireCheck(clients.includes('onClick={clearClientRosterSearch}'),'Clear button must reset both query states')
requireCheck(clients.includes("e.key==='Escape' && clientSearch") && clients.includes('clearClientRosterSearch()'),'Escape clears search')
requireCheck(clients.includes("setClientSearch('')") && clients.includes("setSearchQ('')"),'Clear resets roster and header search')
requireCheck(clients.includes('useEffect(() => { setClientSearch(searchQ) }, [searchQ])'),'Header search integration preserved')
requireCheck(clients.includes("filterStatus==='All'")&&clients.includes("filterRep==='All'")&&clients.includes("filterPipeline==='All'"),'Existing status/rep/stage filters retained')
requireCheck(clients.includes("showArchived ? !!c.archived : !c.archived"),'Archive filter retained')
requireCheck(clients.includes(".eq('tenant_id', myTenantId)"),'Tenant-bound roster fetching retained')
requireCheck(marker==='20261111-roster-search-theme-refresh-501','Current shared release marker')
requireCheck(hotfix.includes(marker),'Bootstrap update guard must match release marker')
requireCheck(html.includes('romylabs-admin-hotfix.js?v='+marker),'New HTML must fetch refreshed guard')
requireCheck(dashboard.includes('Previous CRM tip')&&dashboard.includes('Next CRM tip'),'Final dashboard navigation retained')
console.log('PASS client roster single clear, header reset, selected filters and shared build freshness')
