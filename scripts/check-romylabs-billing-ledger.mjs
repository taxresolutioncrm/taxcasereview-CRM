import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=p=>readFileSync(p,'utf8')
const api=read('supabase/functions/romylabs-stripe-checkout/index.ts')
const webhook=read('supabase/functions/romylabs-stripe-webhook/index.ts')
const settings=read('src/components/admin/RomyLabsStripeSettings.jsx')
const setup=read('src/components/admin/RomyLabsInvoiceSetup.jsx')
const explorer=read('src/components/admin/RomyLabsLedgerExplorer.jsx')
const billing=read('src/components/admin/RomyLabsBilling.jsx')
const has=(source,search,reason)=>assert.ok(source.includes(search),reason)
has(api,"rpc('_is_platform_admin')",'Merchant backend platform-admin auth required')
has(api,"rk_live_",'Use restricted Stripe credentials only')
has(api,"mode:'payment'",'Invoice Checkout remains one-time without uncontrolled subscriptions')
has(api,"invoice.status!=='open'",'Only unpaid open invoices eligible for Checkout')
has(api,"remaining=Number(invoice.amount_cents)-Number(invoice.amount_paid_cents||0)",'Checkout never charges full invoice if partially paid')
has(api,"billing_email:account.billing_email",'Payment invitation must be tied to trusted server account')
has(webhook,"req.headers.get('stripe-signature')",'Webhook must verify Stripe signature')
has(webhook,"Boolean(event.livemode)!==(verifiedMode==='live')",'Webhook cannot cross test/live boundaries')
has(webhook,"event.type==='account.updated'",'Signed account.updated event can verify delivery')
has(webhook,"romylabs_stripe_webhook_events",'Webhook receipts deduplicated')
has(webhook,"checkout.payment_status!=='paid'",'Unpaid Checkout must never mark invoice paid')
has(webhook,"'x-billing-secret':billingSecret",'Internal billing ledger requires secret')
has(settings,"Email Payment Link",'Email draft action for checkout links required')
has(settings,"encodeURIComponent(data.billing_email)",'Email destination from verified server-side account')
has(settings,"window.location.href=href",'Email flow is explicitly user-sent, not falsely claimed sent')
has(setup,"auto_invoice:false,auto_suspend:false",'Six-month accounts cannot silently auto-renew or suspend')
has(setup,"officeRegistry.filter",'Billing account creation requires registered CRM office')
has(setup,"existing=invoices.find",'Duplicate current-month invoice prevented')
has(explorer,"payment-transactions.csv",'Transaction exports provided')
has(explorer,"romylabs-invoices.csv",'Invoice exports provided')
has(explorer,"csvSafe",'CSV formula injection mitigated')
has(explorer,"rows.slice(0,limit)",'Paginated transaction viewer')
has(explorer,"events.filter",'Billing review events surfaced')
has(billing,"<RomyLabsInvoiceSetup",'Billing setup wired to Admin Portal')
has(billing,"<RomyLabsLedgerExplorer",'All-office transaction ledger wired to Admin Portal')
has(billing,"<RomyLabsStripeSettings invoices={invoices} onRefresh={load}/>",'Existing Stripe settings preserved')
assert.ok(!settings.includes('sk_live_'),'Do not instruct use of unrestricted Stripe credentials')
console.log('PASS RomyLabs Stripe payment, invoice and transaction-ledger source contracts')
