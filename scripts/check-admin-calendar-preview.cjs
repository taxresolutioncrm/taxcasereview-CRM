const fs = require('fs')
const assert = require('assert')
const page = fs.readFileSync('src/pages/Calendar.jsx', 'utf8')
const ui = fs.readFileSync('src/components/AdminCalendarPreview.jsx', 'utf8')
const has = (source, needle, message) => assert(source.includes(needle), message)

has(page, 'useState(isRomyLabsAdmin)', 'Unified calendar must be Admin-only by default')
has(page, 'adminCalendarPreviewOpen && !selectedEvent && !showForm && !showBooking',
  'Classic detail, event form and booking modal must still work')
has(page, 'onOpenEvent={event => { setSelectedEvent(event) }}',
  'Events must use the existing CRM event detail')
has(page, 'onBooking={() => { setShowBooking(true) }}',
  'Booking must use the existing modal')
has(page, 'onCreate={(date, selectedProduct) =>',
  'Add event must reuse original CRM form with selected product when valid')
has(page, 'setShowForm(true)', 'Existing form must open')
has(page, 'deadlines={deadlines}', 'Existing deadlines must flow through')
has(page, 'products={calendarProducts}', 'Full product registry must be provided')
has(page, ".from('romylabs_products')", 'Products must come from Admin Portal product registry')
has(page, ".eq('active', true)", 'Only active registry products should be included')
has(page, 'PRODUCT_BOOKING_CONFIGS', 'Booking product config fallback required')
has(page, "key: 'nashville'", 'Separately-hosted Nashville CRM should be listed')
has(ui, 'availableProducts.map(product', 'Product dropdown must use registry entries, not only event rows')
has(ui, 'eventCountByProduct.get(product.key) || 0',
  'Products with no appointments must still appear with 0 count')
has(ui, 'onClick={() => openDay(key)}', 'Clicking each day cell must open selected day')
has(ui, 'onKeyDown={e =>', 'Keyboard day interaction must be available')
has(ui, "e.key === 'Enter' || e.key === ' '", 'Day keyboard controls must work')
has(ui, "aria-label={'Add appointment on ' + key}", 'Each day needs explicit add action')
has(ui, 'onCreate(key, productFilter)', 'Day add action must route to CRM form')
has(ui, 'e.stopPropagation(); onOpenEvent(ev)', 'Event clicks must not trigger day navigation')
has(ui, 'Filter by CRM', 'Product filter required')
has(ui, 'Selected day ·', 'Selected-day agenda required')
has(ui, 'Upcoming deadlines', 'Legacy deadlines retained')
has(ui, "overflowX: 'auto'", 'Mobile horizontal scrolling retained')
has(ui, 'Switch to classic', 'Classic fallback retained')
assert(!ui.includes('supabase.') && !ui.includes('CalendarEvent/set'),
  'Calendar display must not create new data write pathways or use unverified JMAP')
assert(!page.includes('StalwartCalendarWorkspace'),
  'Unverified Stalwart sync must stay outside production')
has(ui, 'aria-label="Day actions"', 'Unified calendar must offer classic day actions')
has(ui, 'onCreate(activeDay, productFilter)', 'Day action new event must use existing CRM handler')
has(ui, "setView('week')", 'Day actions need week view')
has(ui, "setView('day')", 'Day actions need day view')
has(ui, 'aria-expanded={showUpcoming}', 'Upcoming appointments panel must be collapsible')
console.log('PASS unified calendar: full active product registry, day actions, existing CRM handlers and classic fallback')
