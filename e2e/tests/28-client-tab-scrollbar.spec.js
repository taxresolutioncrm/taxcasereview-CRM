const {test,expect}=require('@playwright/test')
const fs=require('fs'),path=require('path')
const src=fs.readFileSync(path.resolve(__dirname,'../../src/pages/Clients.jsx'),'utf8')
const css=fs.readFileSync(path.resolve(__dirname,'../../src/theme-scrollbars.css'),'utf8')
test('client sections use themed scrollbar without navigation arrows',()=>{
 expect(src).toContain('className="client-detail-tabs-scroll"')
 expect(src).toContain("text:'Tax Organizer'")
 expect(src).toContain("overflowX:'auto'")
 expect(src).toContain('aria-selected={detailTab===t.key}')
 expect(src).not.toContain('Scroll client tabs left')
 expect(src).not.toContain('Scroll client tabs right')
 expect(css).toContain('.client-detail-tabs-scroll::-webkit-scrollbar-thumb')
 expect(css).toContain('background: var(--blue)')
 expect(css).toContain('background: var(--s2)')
 expect(css).toContain('touch-action: pan-x pan-y')
})
