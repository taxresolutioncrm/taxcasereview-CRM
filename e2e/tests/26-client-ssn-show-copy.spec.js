const {test,expect}=require('@playwright/test')
const fs=require('fs'),path=require('path')
const ui=fs.readFileSync(path.resolve(__dirname,'../../src/pages/Clients.jsx'),'utf8')
const api=fs.readFileSync(path.resolve(__dirname,'../../supabase/functions/client-sensitive/index.ts'),'utf8')
test('Both taxpayer and spouse have independently controlled Show, Hide, Copy actions',()=>{
 expect(ui).toContain("ssnControl(c.id,'taxpayer')")
 expect(ui).toContain("ssnControl(c.id,'spouse')")
 expect(ui).toContain("visibleSsnFields[field]")
 expect(ui).toContain("copyClientSsn(clientId,field)")
})
test('SSN is masked by default and clears on switch or 30 seconds',()=>{
 expect(ui).toContain("useState({taxpayer:false, spouse:false})")
 expect(ui).toContain("setVisibleSsnFields({taxpayer:false,spouse:false})")
 expect(ui).toContain("},30000)")
 expect(ui).toContain("sensitiveClientRef.current !== clientId")
 expect(ui).toContain("clearTimeout(ssnHideTimer.current)")
})
test('Valid SSN length and clipboard failures are handled without logging values',()=>{
 expect(ui).toContain("const validFullSsn")
 expect(ui).toContain("navigator.clipboard.writeText(formattedFullSsn(value))")
 expect(ui).toContain("Clipboard access blocked or SSN access denied")
 expect(ui).not.toContain("console.log(data.ssn)")
})
test('Backend protects read including both SSNs by tenant and full client permission',()=>{
 expect(api).toContain(".eq('tenant_id',tenantId)")
 expect(api).toContain(".eq('client_id',clientId)")
 expect(api).toContain("if(level<3) return json({error:'Full SSN access requires Full Admin client permission'},403)")
 expect(api).toContain("spouse_ssn: formatSsn(cleanSsn(sensitive?.spouse_ssn))")
})
