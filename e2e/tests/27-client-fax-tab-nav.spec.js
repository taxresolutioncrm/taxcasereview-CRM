const {test,expect}=require('@playwright/test')
const fs=require('fs'),path=require('path')
const clients=fs.readFileSync(path.resolve(__dirname,'../../src/pages/Clients.jsx'),'utf8')
const fax=fs.readFileSync(path.resolve(__dirname,'../../src/pages/Fax.jsx'),'utf8')
test('client tabs retain all sections, readable Tax Organizer and accessible scroll arrows',()=>{
  for(const k of ['overview','notes','tasks','docs','sms','invoices','finprofile','payments','cases','organizer','activity','calls','transactions'])
    expect(clients).toContain("key:'"+k+"'")
  expect(clients).toContain("text:'Tax Organizer'")
  expect(clients).toContain('aria-label="Scroll client tabs left"')
  expect(clients).toContain('aria-label="Scroll client tabs right"')
  expect(clients).toContain('aria-selected={detailTab===t.key}')
  expect(clients).toContain("overflowX:'auto'")
  expect(clients).toContain("clientTabsRef.current?.scrollBy")
  expect(clients).toContain("selected.getBoundingClientRect()")
})
test('fax action sends document identity rather than a privileged storage URL',()=>{
  expect(clients).toContain("faxClientDocument:{documentId:selectedDoc.id,clientId,clientName}")
  expect(fax).toContain(".eq('tenant_id',myTenantId)")
  expect(fax).toContain(".eq('client_id',intent.clientId)")
  expect(fax).toContain("createSignedUrl(storagePath,3600)")
  expect(fax).toContain("setLinkedDocument(null)")
  expect(fax).not.toContain("location.state?.faxClientDocument?.storagePath")
})
