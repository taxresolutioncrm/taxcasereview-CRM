const {test,expect}=require('@playwright/test')
const fs=require('fs')
const path=require('path')
const code=fs.readFileSync(path.resolve(__dirname,'../../src/pages/Clients.jsx'),'utf8')
test('file status control supports Active and Not Active independently of pipeline',()=>{
  expect(code).toContain('data-testid="client-file-status"')
  expect(code).toContain('<option value="Active">Active</option>')
  expect(code).toContain('<option value="Inactive">Not Active</option>')
  expect(code).toContain('onChange={e=>updateFileStatus(e.target.value)}')
})
test('status update requires the current tenant and specific client',()=>{
  const start=code.indexOf('const updateFileStatus=async(')
  const end=code.indexOf('const applyPipelineStage=',start)
  const fn=code.slice(start,end)
  expect(fn).toContain(".update({status:nextStatus})")
  expect(fn).toContain(".eq('tenant_id',myTenantId)")
  expect(fn).toContain(".eq('id',c.id)")
  expect(fn).toContain("['Active','Inactive']")
  expect(fn).not.toContain('archived:')
  expect(fn).not.toContain('pipelineStage:')
})
test('successful update synchronizes detail and list and logs employee note',()=>{
  const fn=code.slice(code.indexOf('const updateFileStatus=async('),code.indexOf('const applyPipelineStage='))
  expect(fn).toContain('setDetail(prev=>')
  expect(fn).toContain('setClients(prev=>')
  expect(fn).toContain('File status changed:')
  expect(fn).toContain('insertClientNote(')
})
