export function translateText(value, language = 'en') {
  if (typeof value !== 'string') return value
  const trimmed = value.trim()
  if (!trimmed) return value
  const map = language === 'es' ? EN_ES : ES_EN
  const translated = map[trimmed]
  if (translated) {
    const start = value.indexOf(trimmed)
    return `${value.slice(0, start)}${translated}${value.slice(start + trimmed.length)}`
  }
  if (language === 'es') {
    for (const [pattern, replacement] of DASHBOARD_PATTERNS) {
      if (pattern.test(trimmed)) {
        const next = trimmed.replace(pattern, replacement)
        const start = value.indexOf(trimmed)
        return `${value.slice(0, start)}${next}${value.slice(start + trimmed.length)}`
      }
    }
  }
  return value
}

function translateNode(node, language) {
  if (!node) return
  if (node.nodeType === Node.TEXT_NODE) {
    const next = translateText(node.nodeValue || '', language)
    if (next !== node.nodeValue) node.nodeValue = next
    return
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return
  const el = node
  if (el.matches?.('script,style,textarea,[data-no-translate]')) return
  for (const attr of ATTRS) {
    if (!el.hasAttribute?.(attr)) continue
    const current = el.getAttribute(attr)
    const next = translateText(current, language)
    if (next !== current) el.setAttribute(attr, next)
  }
  for (const child of el.childNodes || []) translateNode(child, language)
}

export function applyDocumentLanguage(language = 'en') {
  const activeLanguage = language === 'es' ? 'es' : 'en'
  if (typeof document !== 'undefined') document.documentElement.lang = activeLanguage
}

export function getStoredLanguage() {
  try { return localStorage.getItem('tcr-language') === 'es' ? 'es' : 'en' } catch (_) { return 'en' }
}

export function storeLanguage(language) {
  const next = language === 'es' ? 'es' : 'en'
  try { localStorage.setItem('tcr-language', next) } catch (_) {}
  try { window.dispatchEvent(new CustomEvent('taxres-language-change', { detail: { language: next } })) } catch (_) {}
  return next
}

